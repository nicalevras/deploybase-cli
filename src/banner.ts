import { phosphor } from "./formatter.js";

const ART = [
  "      _            _             _                           _ ",
  "   __| | ___ _ __ | | ___  _   _| |__   __ _ ___  ___   __ _(_)",
  "  / _` |/ _ \\ '_ \\| |/ _ \\| | | | '_ \\ / _` / __|/ _ \\ / _` | |",
  " | (_| |  __/ |_) | | (_) | |_| | |_) | (_| \\__ \\  __/| (_| | |",
  "  \\__,_|\\___| .__/|_|\\___/ \\__, |_.__/ \\__,_|___/\\___(_)__,_|_|",
  "            |_|            |___/                               ",
];

export function renderBanner(): string {
  return "\n" + ART.map((line) => phosphor(line)).join("\n") + "\n";
}
